    async def validate_code(self, code: str, language: str = "python") -> Dict[str, Any]:
        """Validate generated code."""
        result = {
            "valid": True,
            "errors": [],
            "warnings": [],
            "metrics": {}
        }
        
        if language == "python":
            try:
                ast.parse(code)
                result["metrics"]["ast_valid"] = True
            except SyntaxError as e:
                result["valid"] = False
                result["errors"].append(str(e))
                result["metrics"]["ast_valid"] = False
            
            # Check for common issues
            if "TODO" in code:
                result["warnings"].append("Code contains TODO comments")
            
            if len(code.split('\n')) < 5:
                result["warnings"].append("Code is very short")
        
        return result
    
    async def self_patch(self, file_path: str, error_trace: str) -> PatchResult:
        """Self-patch a bug by analyzing error trace."""
        logger.info("Self-patching: %s", file_path)
        
        try:
            with open(file_path, 'r') as f:
                original_code = f.read()
        except FileNotFoundError:
            return PatchResult(
                patch_id=str(uuid.uuid4()),
                original_code="",
                patched_code="",
                description=f"File not found: {file_path}",
                tests_passed=False
            )
        
        # Analyze error trace and generate patch
        patched_code = original_code
        
        # Simple pattern-based patching
        if "NameError" in error_trace:
            # Add missing import
            patched_code = "import os\n" + patched_code
        elif "ImportError" in error_trace:
            # Add try/except for import
            patched_code = patched_code.replace(
                "import ",
                "try:\n    import \nexcept ImportError:\n    pass\n"
            )
        
        # Validate patched code
        validation = await self.validate_code(patched_code)
        
        patch_result = PatchResult(
            patch_id=str(uuid.uuid4()),
            original_code=original_code,
            patched_code=patched_code,
            description=f"Auto-patched based on: {error_trace[:100]}",
            tests_passed=validation["valid"],
            tests_output=json.dumps(validation)
        )
        
        self._patches.append(patch_result)
        return patch_result
    
