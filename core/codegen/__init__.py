        """Refactor code for better maintainability."""
        refactored = code
        
        # Remove trailing whitespace
        refactored = '\n'.join(line.rstrip() for line in refactored.split('\n'))
        
        # Ensure consistent indentation (4 spaces)
        lines = []
        for line in refactored.split('\n'):
            # Convert tabs to spaces
            line = line.replace('\t', '    ')
            lines.append(line)
        
        refactored = '\n'.join(lines)
        
        return refactored
    
