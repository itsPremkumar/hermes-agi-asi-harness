"""
Dynamic Workflow Executor — Execute dynamic plans with full orchestrator capacity.

Executes plans generated by the AdvancedPlanningEngine, using:
- Dynamic module selection per step
- Quality gate enforcement
- Real-time decision making
- Parallel execution where possible
- Automatic rollback on failure
"""

