    async def execute_plan(self, plan: DynamicPlan) -> ExecutionResult:
        """
        Execute a dynamic plan with full orchestrator capacity.
        
        This is the main execution entry point.
        """
        start_time = time.time()
        result = ExecutionResult(
            plan_id=plan.id,
            goal=plan.goal,
            status=ExecutionStatus.RUNNING,
        )
        
        try:
            # Execute steps according to topology
            if plan.topology == "single":
                await self._execute_single(plan, result)
            elif plan.topology == "sequential":
                await self._execute_sequential(plan, result)
            elif plan.topology == "parallel":
                await self._execute_parallel(plan, result)
            elif plan.topology == "hierarchical":
                await self._execute_hierarchical(plan, result)
            else:
                await self._execute_sequential(plan, result)
            
            # Determine final status
            if all(r.status == ExecutionStatus.COMPLETED for r in result.step_results):
                result.status = ExecutionStatus.COMPLETED
            elif any(r.status == ExecutionStatus.FAILED for r in result.step_results):
                result.status = ExecutionStatus.FAILED
            else:
                result.status = ExecutionStatus.COMPLETED
            
        except Exception as e:
            result.status = ExecutionStatus.FAILED
            result.error = str(e)
        
        result.total_duration_ms = (time.time() - start_time) * 1000
        return result
    
    async def _execute_single(self, plan: DynamicPlan, result: ExecutionResult):
        """Execute all steps sequentially in a single thread."""
        for step in plan.steps:
            step_result = await self._execute_step(step, plan)
            result.step_results.append(step_result)
            
            if step_result.status == ExecutionStatus.FAILED:
                # Make a decision about what to do
                decisions = self.decision_engine.evaluate_step_completion(step, step_result.output)
                step_result.decisions = decisions
    
    async def _execute_sequential(self, plan: DynamicPlan, result: ExecutionResult):
        """Execute steps sequentially, respecting dependencies."""
        completed = set()
        remaining = list(plan.steps)
        
        while remaining:
            # Find steps that are ready (all dependencies completed)
            ready = [
                s for s in remaining
                if all(dep in completed for dep in s.depends_on)
            ]
            
            if not ready:
                # Deadlock - break
                break
            
            for step in ready:
                step_result = await self._execute_step(step, plan)
                result.step_results.append(step_result)
                
                if step_result.status == ExecutionStatus.COMPLETED:
                    completed.add(step.id)
                    remaining.remove(step)
                else:
                    # Handle failure
                    decisions = self.decision_engine.evaluate_step_completion(step, step_result.output)
                    step_result.decisions = decisions
                    
                    # Check if we should rollback
                    rollback_decision = self.decision_engine.should_rollback(step, step_result.output)
                    if rollback_decision:
                        result.status = ExecutionStatus.ROLLED_BACK
                        return
    
    async def _execute_parallel(self, plan: DynamicPlan, result: ExecutionResult):
        """Execute independent steps in parallel."""
        completed = set()
        remaining = list(plan.steps)
        
        while remaining:
            # Find steps that are ready
            ready = [
                s for s in remaining
                if all(dep in completed for dep in s.depends_on)
            ]
            
            if not ready:
                break
            
            # Execute ready steps in parallel (up to max_parallelism)
            batch = ready[:plan.max_parallelism]
            tasks = [self._execute_step(step, plan) for step in batch]
            batch_results = await asyncio.gather(*tasks, return_exceptions=True)
            
            for step, step_result in zip(batch, batch_results):
                if isinstance(step_result, Exception):
                    step_result = StepResult(
                        step_id=step.id,
                        status=ExecutionStatus.FAILED,
                        error=str(step_result),
                    )
                result.step_results.append(step_result)
                
                if step_result.status == ExecutionStatus.COMPLETED:
                    completed.add(step.id)
                    remaining.remove(step)
    
    async def _execute_hierarchical(self, plan: DynamicPlan, result: ExecutionResult):
        """Execute steps hierarchically (manager -> workers)."""
        # Group steps by level (based on dependency depth)
        levels = self._compute_step_levels(plan.steps)
        
        for level_steps in levels:
            # Execute each level in parallel
            tasks = [self._execute_step(step, plan) for step in level_steps]
            level_results = await asyncio.gather(*tasks, return_exceptions=True)
            
            for step, step_result in zip(level_steps, level_results):
                if isinstance(step_result, Exception):
                    step_result = StepResult(
                        step_id=step.id,
                        status=ExecutionStatus.FAILED,
                        error=str(step_result),
                    )
                result.step_results.append(step_result)
    
    def _compute_step_levels(self, steps: list[PlanStep]) -> list[list[PlanStep]]:
        """Compute execution levels based on dependency depth."""
        step_map = {s.id: s for s in steps}
        levels: dict[int, list[PlanStep]] = {}
        
        def get_depth(step: PlanStep, visited: set | None = None) -> int:
            if visited is None:
                visited = set()
            if step.id in visited:
                return 0
            visited.add(step.id)
            
            if not step.depends_on:
                return 0
            
            max_dep_depth = 0
            for dep_id in step.depends_on:
                dep_step = step_map.get(dep_id)
                if dep_step:
                    max_dep_depth = max(max_dep_depth, get_depth(dep_step, visited) + 1)
            
            return max_dep_depth
        
        for step in steps:
            depth = get_depth(step)
            if depth not in levels:
                levels[depth] = []
            levels[depth].append(step)
        
        return [levels[k] for k in sorted(levels.keys())]
    
    async def _execute_step(self, step: PlanStep, plan: DynamicPlan) -> StepResult:
        """Execute a single plan step."""
        start_time = time.time()
        
        try:
            # Execute each required module for this step
            outputs = {}
            for module_name in step.required_modules:
                executor = self._module_registry.get(module_name)
                if executor:
                    output = await executor(step, plan)
                    outputs[module_name] = output
            
            return StepResult(
                step_id=step.id,
                status=ExecutionStatus.COMPLETED,
                output=outputs,
                duration_ms=(time.time() - start_time) * 1000,
            )
        
        except Exception as e:
            return StepResult(
                step_id=step.id,
                status=ExecutionStatus.FAILED,
                error=str(e),
                duration_ms=(time.time() - start_time) * 1000,
            )
    
