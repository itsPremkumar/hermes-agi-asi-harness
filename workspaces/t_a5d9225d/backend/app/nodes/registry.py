    """Definition of a workflow node type."""
    type: str
    name: str
    category: str
    description: str
    icon: str = "box"
    color: str = "#6366f1"
    inputs: list = field(default_factory=list)
    outputs: list = field(default_factory=list)
    config_schema: dict = field(default_factory=dict)


