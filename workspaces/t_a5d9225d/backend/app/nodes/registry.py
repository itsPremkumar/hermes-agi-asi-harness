def get_node_registry() -> dict[str, NodeDefinition]:
    """Get all node definitions as a dict keyed by type."""
    return {n.type: n for n in NODE_DEFINITIONS}


def get_nodes_by_category() -> dict[str, list[NodeDefinition]]:
    """Get nodes grouped by category."""
    cats: dict[str, list[NodeDefinition]] = {}
    for n in NODE_DEFINITIONS:
        cats.setdefault(n.category, []).append(n)
    return cats


def get_node(type_name: str) -> NodeDefinition | None:
    """Get a single node definition by type."""
    return get_node_registry().get(type_name)
