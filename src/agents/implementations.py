    async def stop(self) -> bool:
        logger.info("Planner agent stopped")
        return True
    
    async def create_plan(self, goal: str) -> dict[str, Any]:
        """Create an execution plan for a goal using MCTS and topological decomposition."""
        try:
            from hermes_agi.thinking import DeepThinkingEngine
            engine = DeepThinkingEngine()
            thought_res = await engine.think(goal, use_mcts=True)
            plan_steps = thought_res.get("plan", [])
            if not plan_steps:
                plan_steps = [
                    {"id": "step-1", "action": "research", "description": f"Gather context for {goal}"},
                    {"id": "step-2", "action": "implement", "description": f"Execute implementation for {goal}"},
                    {"id": "step-3", "action": "verify", "description": f"Validate criteria for {goal}"},
                ]
            return {
                "goal": goal,
                "steps": plan_steps,
                "dependencies": {s["id"]: [] for s in plan_steps},
                "estimated_time": len(plan_steps) * 30,
                "strategy": thought_res.get("best_strategy", "mcts_deliberative"),
            }
        except Exception:
            steps = [
                {"id": "step-1", "action": "research", "description": f"Analyze requirements: {goal}"},
                {"id": "step-2", "action": "implement", "description": f"Construct solution: {goal}"},
                {"id": "step-3", "action": "verify", "description": f"Verify correctness: {goal}"},
            ]
            return {
                "goal": goal,
                "steps": steps,
                "dependencies": {"step-2": ["step-1"], "step-3": ["step-2"]},
                "estimated_time": 90,
                "strategy": "heuristic_decomposition",
            }


